const estaDentroDeAntigua = (latitud, longitud) => {
  const x = longitud;
  const y = latitud;
  let dentro = false;
  const epsilon = 1e-10;

  for (let i = 0, j = LIMITE_ANTIGUA.length - 1; i < LIMITE_ANTIGUA.length; j = i++) {
    const [xi, yi] = LIMITE_ANTIGUA[i];
    const [xj, yj] = LIMITE_ANTIGUA[j];

    // Acepta puntos exactamente sobre el límite.
    const area = (x - xi) * (yj - yi) - (y - yi) * (xj - xi);
    const sobreSegmento =
      Math.abs(area) <= epsilon &&
      x >= Math.min(xi, xj) - epsilon &&
      x <= Math.max(xi, xj) + epsilon &&
      y >= Math.min(yi, yj) - epsilon &&
      y <= Math.max(yi, yj) + epsilon;

    if (sobreSegmento) return true;

    const cruza =
      (yi > y) !== (yj > y) &&
      x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;

    if (cruza) dentro = !dentro;
  }

  return dentro;
};

